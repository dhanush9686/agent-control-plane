// GET /api/data?file=<name> -> data for a logged-in visitor only.
//   file=users     the account register and recent sign-ins (admins only)
//   file=approvals drafted refunds waiting for a person, and decided ones (Redis only)
//   file=report    what the latest compliance report covers (the report itself is /api/report)
//   file=sim       guardrail-simulator jobs and their results (Redis only)
//   file=events    live webhook events and their agent steps (Redis only)
//   file=live      the newest synced results from Redis (or the bundled copy when Redis is not configured)
//   anything else  a file bundled into this function (api/_data.js, generated by scripts/build_dashboard.py)
const users = require("./_users");
const { readLive, readEvents, readSim, readApprovals, readReportMeta } = require("./_redis");

module.exports = async (req, res) => {
  res.setHeader("Cache-Control", "private, no-store");
  const session = await users.authenticate(req);
  if (!session) return res.status(401).json({ error: "Login required." });
  const bundle = require("./_data");
  const file = String((req.query && req.query.file) || "");

  if (file === "users") {
    if (session.role !== "admin") return res.status(403).json({ error: "Admins only." });
    try {
      return res.status(200).json(await users.listUsers());
    } catch (_) {
      return res.status(502).json({ error: "The account register could not be reached." });
    }
  }

  if (file === "approvals") {
    try {
      return res.status(200).json(await readApprovals());
    } catch (_) {
      return res.status(502).json({ error: "The approvals store could not be reached." });
    }
  }

  if (file === "report") {
    try {
      return res.status(200).json(await readReportMeta());
    } catch (_) {
      return res.status(502).json({ error: "The report store could not be reached." });
    }
  }

  if (file === "sim") {
    try {
      return res.status(200).json(await readSim(session.role === "admin"));
    } catch (_) {
      return res.status(502).json({ error: "The simulator store could not be reached." });
    }
  }

  if (file === "events") {
    try {
      return res.status(200).json(await readEvents());
    } catch (_) {
      return res.status(502).json({ error: "The event store could not be reached." });
    }
  }

  if (file === "live") {
    let live;
    try {
      live = await readLive();
    } catch (_) {
      return res.status(502).json({ error: "The live data store could not be reached." }); // never echo details
    }
    if (live) return res.status(200).json(live);
    if (Object.prototype.hasOwnProperty.call(bundle, "live")) return res.status(200).json({ ...bundle.live, via: "bundle" });
    return res.status(404).json({ error: "Live data is not configured." });
  }

  if (!Object.prototype.hasOwnProperty.call(bundle, file)) return res.status(404).json({ error: "No such data file." });
  return res.status(200).json(bundle[file]);
};
