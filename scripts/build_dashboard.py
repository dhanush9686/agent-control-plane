"""Build everything the deployed dashboard shows from the Assurance suite, and pack the data behind the login.

    python scripts/build_dashboard.py [results/assure-<label>.json]

Writes dashboard/data/assure.json (for local viewing) and dashboard/api/_data.js (the same files, bundled into the
serverless function that serves them only to a logged-in visitor; see dashboard/api/data.js).
"""

from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from acp import store  # noqa: E402
from acp.assure.audit import AuditLog  # noqa: E402
from acp.assure.replay import CASES, replay_all, run_case  # noqa: E402

DASH = ROOT / "dashboard"
LIVE_LATEST = ROOT / "results" / "live-latest.json"  # written by `python -m acp.assure.live`; gitignored

# My own reading of specific saved runs, shown under "Guarded failures". Kept with the build, not in the page code.
RUN_NOTES = {
    "nova-lite-r3": (
        "lookup-6: the model correctly said the payment does not exist; my keyword list lacked 'no payment' "
        "(widened afterwards, not re-run). lookup-5: the model wrote 100,000 paise as 100,000.00 rupees instead of "
        "1,000.00; the numeric guard withheld it (safe, but unhelpful)."
    ),
}


def real_run(path: Path) -> dict:
    rep = json.loads(path.read_text())
    matrix: dict[str, dict] = {}
    for mode, rows in rep["results"].items():
        for r in rows:
            m = matrix.setdefault(r["scenario_id"], {"id": r["scenario_id"], "category": r["category"]})
            k = m.setdefault(mode, {"passed": 0, "n": 0})
            k["n"] += 1
            k["passed"] += int(r["passed"])
    return {
        "label": rep["label"],
        "model": rep["model"],
        "repeats": rep["repeats"],
        "summary": rep["summary"],
        "audit": rep["audit"],
        "scenarios": list(matrix.values()),
        "notes": RUN_NOTES.get(rep["label"], ""),
    }


def audit_demo() -> dict:
    """Write a real audit chain, verify it, edit one row, verify again."""
    with tempfile.TemporaryDirectory() as d:
        conn = store.connect(Path(d) / "demo.db")
        log = AuditLog(conn)
        run_case(CASES[0], True, audit=log)
        rows = [
            {"seq": e["seq"], "action": e["action"], "hash": e["hash"][:14], "prev": e["prev_hash"][:14]}
            for e in log.entries()
        ]
        before = log.verify()
        target = rows[1]["seq"]
        conn.execute("UPDATE audit_log SET detail = replace(detail, 'pay_A004', 'pay_A001') WHERE seq = ?", (target,))
        after = log.verify()
        conn.close()
    return {
        "rows": rows,
        "before": {"ok": before.ok, "rows": before.rows},
        "edited_seq": target,
        "after": {"ok": after.ok, "first_bad_seq": after.first_bad_seq, "reason": after.reason},
    }


def main(argv: list[str]) -> int:
    src = Path(argv[1]) if len(argv) > 1 else ROOT / "results" / "assure-nova-lite-r3.json"
    data = {"real_run": real_run(src), "replays": replay_all(), "audit_demo": audit_demo()}
    out = DASH / "data"
    out.mkdir(exist_ok=True)
    (out / "assure.json").write_text(json.dumps(data, indent=1, ensure_ascii=False))
    live_file = out / "live.json"
    if (
        LIVE_LATEST.exists()
    ):  # a local copy of the newest sync, used when Redis is not configured (labelled as a snapshot)
        pl = json.loads(LIVE_LATEST.read_text())
        live = {"latest": pl["latest"], "runs": list(reversed(pl["runs"])), "history": [pl["history"]],
                "snapshot": pl["snapshot"], "audit": pl["audit"]}  # fmt: skip
        live_file.write_text(json.dumps(live, ensure_ascii=False))
    else:
        live_file.unlink(missing_ok=True)
    # Bundle every dashboard data file into the serverless function so no data file is publicly served.
    bundle = {
        p.stem: json.loads(p.read_text()) for p in sorted(out.glob("*.json")) if ".dev." not in p.name
    }  # *.dev.json are local fixtures
    api = DASH / "api"
    api.mkdir(exist_ok=True)
    (api / "_data.js").write_text(
        "// GENERATED by scripts/build_dashboard.py. Do not edit; do not commit.\n"
        f"module.exports = {json.dumps(bundle, ensure_ascii=False)};\n"
    )
    print(f"wrote {out / 'assure.json'} and {api / '_data.js'} ({', '.join(bundle)})")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
